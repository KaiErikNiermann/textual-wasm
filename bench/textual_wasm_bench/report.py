"""Render a result file as the Markdown tables `docs/benchmarks.md` includes.

Generated rather than written by hand, so the documentation cannot quote a number the
committed results do not contain; `report --check` is the gate that keeps them in step.

Columns are one per engine and interpreter placement, plus `native` - the same app or
workload on CPython - wherever there is a native counterpart. Rows that are layers carry a
`+` column: the difference from the layer below, which is the cost of the layer added.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any, Final

from textual_wasm_bench import results
from textual_wasm_bench.plan import Layer, Mode
from textual_wasm_bench.summary import median, p95, slope

Column = tuple[str, str]
"""An (engine, mode) pair."""

Cell = Callable[[results.Record], float | None]

Summary = Callable[[list[float]], float | None]

NATIVE: Final[Column] = ("native", str(Mode.NONE))

MIB: Final[float] = float(1 << 20)

WHOLE_NUMBERS_FROM: Final[float] = 100.0
"""Past this, decimals are noise and only make a table harder to read."""

GENERATED_NOTE: Final[str] = (
    "<!-- Generated by `just bench-report` from bench/results/. Do not edit. -->"
)


def _columns(data: results.ResultFile) -> list[Column]:
    seen: list[Column] = []
    for record in data["records"].values():
        column = (record["engine"], record["mode"])
        if record["engine"] != "native" and record["mode"] != str(Mode.NONE) and column not in seen:
            seen.append(column)
    return seen


def _record(data: results.ResultFile, column: Column, case: str) -> results.Record | None:
    engine, mode = column
    records = data["records"]
    return records.get(f"{engine}/{mode}/{case}") or records.get(f"{engine}/-/{case}")


def _format(value: float | None, digits: int = 1) -> str:
    if value is None:
        return "-"
    if abs(value) >= WHOLE_NUMBERS_FROM:
        return f"{value:,.0f}"
    return f"{value:.{digits}f}"


def _params(data: results.ResultFile, case: str) -> dict[str, Any]:
    """The parameters `case` ran with, from whichever record has them first."""
    for record in data["records"].values():
        if record["case"] == case:
            return record["params"]
    return {}


def _signed(value: float | None, digits: int) -> str:
    """A difference, always signed, with a rounded-away negative zero shown as +0."""
    if value is None:
        return ""
    rounded = round(value, digits) or 0.0
    return f"{'+' if rounded >= 0 else ''}{_format(rounded, digits)}"


def _header(first: str, columns: Sequence[Column]) -> list[str]:
    names = ["native" if column == NATIVE else f"{column[0]} {column[1]}" for column in columns]
    return [
        f"| {first} | {' | '.join(names)} |",
        f"|---|{'---|' * len(columns)}",
    ]


def _table(
    data: results.ResultFile,
    rows: Sequence[tuple[str, str, Cell]],
    columns: Sequence[Column],
    digits: int = 1,
) -> list[str]:
    """One row per (label, case, cell); one column per engine and mode."""
    lines = _header("", columns)
    for label, case, cell in rows:
        values = [
            _format(
                None if (record := _record(data, column, case)) is None else cell(record), digits
            )
            for column in columns
        ]
        lines.append(f"| {label} | {' | '.join(values)} |")
    return lines


# --- idle ------------------------------------------------------------------------------


def _per_run(
    record: results.Record, pick: Callable[[dict[str, Any]], float | None]
) -> float | None:
    values = [value for run in record["runs"] if (value := pick(run)) is not None]
    return median(values)


def _cpu_percent(record: results.Record) -> float | None:
    return _per_run(record, lambda run: run["cpuMs"] / run["windowMs"] * 100)


def _rate(key: str) -> Cell:
    def cell(record: results.Record) -> float | None:
        return _per_run(
            record,
            lambda run: None if run.get(key) is None else run[key] / run["windowMs"] * 1000,
        )

    return cell


def _main_thread(key: str) -> Cell:
    """Milliseconds per second the page's main thread spent on `key`, per Chromium."""

    def cell(record: results.Record) -> float | None:
        return _per_run(
            record,
            lambda run: (
                None
                if run.get("mainThread") is None
                else run["mainThread"][key] / run["windowMs"] * 1000
            ),
        )

    return cell


def _layered(
    data: results.ResultFile, scenario: str, columns: Sequence[Column], cell: Cell, digits: int
) -> list[str]:
    """A layer table's rows: each layer's value and what it adds over the one below."""
    lines: list[str] = []
    previous: dict[Column, float | None] = {}
    for layer in Layer:
        values: list[str] = []
        for column in columns:
            record = _record(data, column, f"{scenario}/{layer}")
            value = None if record is None else cell(record)
            below = previous.get(column)
            added = (
                None if value is None or below is None or layer is Layer.INPUT else value - below
            )
            values.extend((_format(value, digits), _signed(added, digits)))
            if layer is not Layer.INPUT:
                previous[column] = value
        lines.append(f"| {layer} | {' | '.join(values)} |")
    return lines


def _layer_header(columns: Sequence[Column]) -> list[str]:
    names = [f"{engine} {mode}" for engine, mode in columns]
    cells = " | ".join(f"{name} | +" for name in names)
    return [f"| layer | {cells} |", f"|---|{'---|---|' * len(columns)}"]


def _layer_table(
    data: results.ResultFile, scenario: str, columns: Sequence[Column], cell: Cell, digits: int = 1
) -> list[str]:
    return [*_layer_header(columns), *_layered(data, scenario, columns, cell, digits)]


def _idle(data: results.ResultFile, columns: list[Column]) -> list[str]:
    native_rows = [
        ("static app", "idle/app", _cpu_percent),
        ("blinking input", "idle/input", _cpu_percent),
    ]
    return [
        "### Idle CPU",
        "",
        (
            "Percent of one core used by the whole browser (every process it runs) while the page "
            "sits untouched, median of the runs. `+` is what the layer adds over the one above it; "
            "`input` is measured against the same floor as `app` and has no `+`."
        ),
        "",
        *_layer_table(data, "idle", columns, _cpu_percent, 2),
        "",
        "The same two apps on a real terminal, through Textual's own driver:",
        "",
        *_table(data, native_rows, [NATIVE], 2),
        "",
        "### What an idle page redraws",
        "",
        (
            "Terminal writes per second and characters per second while idle - a count, so it is "
            "exact rather than a reading. `native` counts the bytes the app wrote to its pty."
        ),
        "",
        *_table(
            data,
            [
                ("static app: writes/s", "idle/app", _rate("writes")),
                ("static app: characters/s", "idle/app", _rate("characters")),
                ("blinking input: writes/s", "idle/input", _rate("writes")),
                ("blinking input: characters/s", "idle/input", _rate("characters")),
            ],
            [*columns, NATIVE],
        ),
        "",
        "### Where the main thread's idle time goes (Chromium)",
        "",
        (
            "Milliseconds per second of the page's main thread, from Chromium's own accounting. "
            "In a worker build the interpreter is not on this thread, so its time is not here."
        ),
        "",
        *_table(
            data,
            [
                (f"{layer}: {kind}", f"idle/{layer}", _main_thread(key))
                for layer in (Layer.TICK, Layer.APP, Layer.INPUT)
                for kind, key in (("all tasks", "taskMs"), ("script", "scriptMs"))
            ],
            [column for column in columns if column[0] == "chromium"],
            2,
        ),
    ]


# --- boot and memory -------------------------------------------------------------------


def _mark_gap(start: str | None, end: str) -> Cell:
    """Median milliseconds between two boot marks; from navigation when `start` is None."""

    def cell(record: results.Record) -> float | None:
        def gap(run: dict[str, Any]) -> float | None:
            marks: dict[str, float] = run["marks"]
            if end not in marks or (start is not None and start not in marks):
                return None
            return marks[end] - (0.0 if start is None else marks[start])

        return _per_run(record, gap)

    return cell


def _boot(data: results.ResultFile, columns: list[Column]) -> list[str]:
    phases = [
        ("page and terminal loaded", None, "interpreter"),
        ("interpreter boot", "interpreter", "packages"),
        ("packages installed", "packages", "app"),
        ("app started and drawn", "app", "ready"),
        ("total, navigation to running", None, "ready"),
    ]
    rows: list[tuple[str, str, Cell]] = [
        (f"{label} (first visit)", "boot/app", _mark_gap(start, end))
        for label, start, end in phases
    ]
    rows += [
        (f"{label} (cached)", "boot/app-warm", _mark_gap(start, end))
        for label, start, end in phases
    ]
    return [
        "### Boot time",
        "",
        (
            "Milliseconds, median of the runs, split at the page's own boot marks. A first visit "
            "downloads the interpreter and the wheels from the CDN, so its numbers depend on the "
            "network as much as on the machine; the cached rows are a reload."
        ),
        "",
        *_table(data, rows, columns, 0),
    ]


def _memory_cell(pick: Callable[[dict[str, Any]], float | None]) -> Cell:
    return lambda record: _per_run(record, lambda run: pick(run["memory"]))


def _pss(memory: dict[str, Any]) -> float | None:
    pss = memory["tree"]["pssBytes"]
    return None if pss is None else pss / MIB


def _memory(data: results.ResultFile, columns: list[Column]) -> list[str]:
    heap = _memory_cell(lambda m: None if m["heap"] is None else m["heap"]["usedBytes"] / MIB)
    interpreter_rows: list[tuple[str, str, Cell]] = [
        (
            "WebAssembly memory (MiB)",
            "boot/app",
            _memory_cell(
                lambda m: (
                    None
                    if m["interpreter"] is None or m["interpreter"]["wasm_bytes"] is None
                    else m["interpreter"]["wasm_bytes"] / MIB
                )
            ),
        ),
        (
            "Python objects tracked by gc",
            "boot/app",
            _memory_cell(
                lambda m: None if m["interpreter"] is None else m["interpreter"]["gc_objects"]
            ),
        ),
    ]
    return [
        "### Memory",
        "",
        (
            "Proportional set size of the whole browser in MiB once each layer is up and settled - "
            "shared pages divided between the processes sharing them, so the column sums to what "
            "the browser holds. `+` is what each layer adds."
        ),
        "",
        *_layer_table(data, "boot", columns, _memory_cell(_pss), 0),
        "",
        (
            "The page's JavaScript heap after a forced collection (Chromium; a worker's "
            "heap is not the page's and is not included), in MiB:"
        ),
        "",
        *_layer_table(data, "boot", [c for c in columns if c[0] == "chromium"], heap),
        "",
        "From inside the interpreter, with the app running:",
        "",
        *_table(data, interpreter_rows, columns, 0),
    ]


# --- the data channel ------------------------------------------------------------------


def _samples(record: results.Record, *keys: str) -> list[float]:
    found: list[float] = []
    for run in record["runs"]:
        node: Any = run
        for key in keys:
            node = node[key]
        found.extend(node)
    return found


def _drain_total(record: results.Record) -> float | None:
    return median([run["totalMs"] for run in record["runs"][0]["runs"]])


def _drain_rate(record: results.Record) -> float | None:
    total = _drain_total(record)
    count = record["runs"][0]["count"]
    return None if not total else count / total * 1000


def _payload(size: int) -> Cell:
    def cell(record: results.Record) -> float | None:
        for entry in record["runs"][0]["results"]:
            if entry["bytes"] == size:
                return median(entry["samples"])
        return None

    return cell


def _channel(data: results.ResultFile, columns: list[Column]) -> list[str]:
    first = _params(data, "payload")
    sizes: list[int] = first.get("sizes", [])
    drain_params = _params(data, "drain")
    flood_params = _params(data, "flood")
    rows: list[tuple[str, str, Cell]] = [
        ("round trip, median (ms)", "latency", lambda r: median(_samples(r, "samples"))),
        ("round trip, p95 (ms)", "latency", lambda r: p95(_samples(r, "samples"))),
        (f"{drain_params.get('n', 0):,} messages, sent and handled (ms)", "drain", _drain_total),
        ("messages handled per second", "drain", _drain_rate),
        (
            f"{flood_params.get('n', 0):,} messages: sending (ms)",
            "flood",
            lambda r: r["runs"][0]["runs"][0]["sendMs"],
        ),
        (
            f"{flood_params.get('n', 0):,} messages: until all handled (ms)",
            "flood",
            lambda r: r["runs"][0]["runs"][0]["totalMs"],
        ),
        (
            f"{flood_params.get('n', 0):,} messages: received",
            "flood",
            lambda r: r["runs"][0]["runs"][0]["received"],
        ),
        *[(f"{size / MIB:g} MiB round trip (ms)", "payload", _payload(size)) for size in sizes],
        ("`sendLatest` calls in one frame", "latest", lambda r: r["runs"][0]["calls"]),
        ("... messages the app received", "latest", lambda r: r["runs"][0]["received"]),
        (
            "longest frame gap during a burst (ms)",
            "stall",
            lambda r: median(_samples(r, "burstGapMs")),
        ),
        ("longest frame gap, no burst (ms)", "stall", lambda r: median(_samples(r, "quietGapMs"))),
    ]
    return [
        "### The data channel",
        "",
        (
            "Timed inside the page, median of the repeats. The burst row is the longest gap "
            "between two animation frames while the page sends a burst and the app handles it; "
            "the row under it is the same measurement with no burst, which is what one frame is "
            "on this machine."
        ),
        "",
        *_table(data, rows, columns, 2),
    ]


def _control_cell(name: str) -> Cell:
    def cell(record: results.Record) -> float | None:
        return median(_samples(record, name, "samples"))

    return cell


def _native_drain(record: results.Record) -> float | None:
    return median([run["totalMs"] for run in record["runs"][0]["drain"]["runs"]])


def _controls(data: results.ResultFile, columns: list[Column]) -> list[str]:
    params = _params(data, "control")
    drain_params = _params(data, "drain")
    rows: list[tuple[str, str, Cell]] = [
        (
            f"pure-Python loop, {params.get('spin', 0):,} iterations",
            "control",
            _control_cell("spin"),
        ),
        (
            f"Textual message pump, {params.get('selfFlood', 0):,} self-posted messages",
            "control",
            _control_cell("selfFlood"),
        ),
        (
            f"mount and remove {params.get('churn', 0):,} widgets",
            "control",
            _control_cell("churn"),
        ),
    ]
    native = [*columns, NATIVE]
    drain_rows: list[tuple[str, str, Cell]] = [
        (f"{drain_params.get('n', 0):,} messages through the channel", "drain", _drain_total),
    ]
    native_drain = _table(
        data,
        [
            (
                f"{drain_params.get('n', 0):,} messages, bridge called directly",
                "control",
                _native_drain,
            )
        ],
        [NATIVE],
        2,
    )
    return [
        "### Whose cost: interpreter, Textual, or channel",
        "",
        (
            "The same workloads, timed from inside Python, in every runtime. The loop touches "
            "nothing but the interpreter, so the ratio between its native and browser columns is "
            "what the interpreter costs; a workload whose ratio matches it is slow because of the "
            "interpreter rather than anything on top. Milliseconds, median."
        ),
        "",
        *_table(data, rows, native, 2),
        "",
        (
            "The channel's throughput, against the bridge and Textual's message queue with the "
            "page, the transport and the browser removed (native, the bridge's callback called "
            "directly):"
        ),
        "",
        *_table(data, drain_rows, columns, 2),
        "",
        *native_drain,
    ]


# --- leaks -----------------------------------------------------------------------------


def _readings(record: results.Record) -> list[dict[str, Any]]:
    return record["runs"][0]["readings"]


def _late_slope(values: list[float]) -> float | None:
    """Growth per round over the second half: after caches and first-use costs settle."""
    return slope(values[len(values) // 2 :])


def _series(
    pick: Callable[[dict[str, Any]], float | None],
) -> Callable[[results.Record], list[float]]:
    return lambda record: [v for reading in _readings(record) if (v := pick(reading)) is not None]


def _leak_rows(case: str) -> list[tuple[str, str, Cell]]:
    objects = _series(lambda r: r["interpreter"]["gc_objects"])
    heap = _series(lambda r: None if r["heap"] is None else r["heap"]["usedBytes"] / 1024)
    pss = _series(lambda r: None if r["tree"]["pssBytes"] is None else r["tree"]["pssBytes"] / MIB)
    wasm = _series(
        lambda r: (
            None if r["interpreter"]["wasm_bytes"] is None else r["interpreter"]["wasm_bytes"] / MIB
        )
    )
    return [
        ("Python objects: before", case, lambda r: (objects(r) or [None])[0]),
        ("Python objects: after", case, lambda r: (objects(r) or [None])[-1]),
        ("Python objects per round, second half", case, lambda r: _late_slope(objects(r))),
        ("page JS heap KiB per round, second half", case, lambda r: _late_slope(heap(r))),
        ("WebAssembly MiB: before", case, lambda r: (wasm(r) or [None])[0]),
        ("WebAssembly MiB: after", case, lambda r: (wasm(r) or [None])[-1]),
        ("browser PSS MiB per round, second half", case, lambda r: _late_slope(pss(r))),
    ]


def _native_leak(key: str) -> Callable[[results.Record], list[float]]:
    """The native control's object counts for one workload, empty if the run predates it."""

    def series(record: results.Record) -> list[float]:
        workload = record["runs"][0].get(key)
        return [] if workload is None else [r["gc_objects"] for r in workload["interpreter"]]

    return series


def _over(series: Callable[[results.Record], list[float]], pick: Summary) -> Cell:
    """A cell that summarises a series read from the record."""
    return lambda record: pick(series(record))


def _first(values: list[float]) -> float | None:
    return values[0] if values else None


def _last(values: list[float]) -> float | None:
    return values[-1] if values else None


def _rounds(values: list[float]) -> float | None:
    return float(len(values) - 1) if values else None


def _native_leak_rows() -> list[tuple[str, str, Cell]]:
    picks: tuple[tuple[str, Summary], ...] = (
        ("rounds", _rounds),
        ("Python objects before", _first),
        ("Python objects after", _last),
        ("Python objects per round, second half", _late_slope),
    )
    return [
        (f"{label}: {name}", "control", _over(_native_leak(key), pick))
        for label, key in (("messages", "leakBridge"), ("widgets", "leakChurn"))
        for name, pick in picks
    ]


def _leaks(data: results.ResultFile, columns: list[Column]) -> list[str]:
    bridge = _params(data, "leak/bridge")
    churn = _params(data, "leak/churn")
    return [
        "### Leaks",
        "",
        (
            "A workload repeated in rounds, with memory read after each from every vantage point "
            "and a full collection first. Growth that continues into the second half is a leak, "
            "and the row it shows in says whose: Python objects are Python, the JS heap is the "
            "page, PSS is everything including the interpreter's linear memory."
        ),
        "",
        (
            f"**Messages**: {bridge.get('rounds', 0)} rounds of {bridge.get('perRound', 0):,} "
            "messages through the channel."
        ),
        "",
        *_table(data, _leak_rows("leak/bridge"), columns, 2),
        "",
        (
            f"**Widgets**: {churn.get('rounds', 0)} rounds of mounting and removing "
            f"{churn.get('perRound', 0):,} widgets."
        ),
        "",
        *_table(data, _leak_rows("leak/churn"), columns, 2),
        "",
        (
            "Both workloads natively, under `App.run_test`, for more rounds - each costs "
            "milliseconds there - so that caches filling can be told apart from a leak:"
        ),
        "",
        *_table(data, _native_leak_rows(), [NATIVE], 2),
    ]


# --- the page --------------------------------------------------------------------------


def _environment(data: results.ResultFile) -> list[str]:
    env = data["environment"]
    browsers = sorted(
        {
            f"{record['engine']} {record['browser_version']}"
            for record in data["records"].values()
            if "browser_version" in record
        }
    )
    commit = f"{env['commit']}{' (with uncommitted changes)' if env['dirty'] else ''}"
    later = sorted(
        {
            stamp
            for record in data["records"].values()
            if (stamp := record.get("commit")) is not None and stamp != env["commit"]
        }
    )
    if later:
        commit += f"`; some records re-measured at `{'`, `'.join(later)}"
    return [
        "### The machine",
        "",
        "| | |",
        "|---|---|",
        f"| measured | {env['date']} at `{commit}`, profile `{data['profile']}` |",
        f"| CPU | {env['cpu']}, {env['cores']} threads |",
        f"| memory | {env['memory_bytes'] / (1 << 30):.0f} GiB |",
        f"| OS | {env['os']} |",
        f"| browsers | {', '.join(browsers)} (Playwright builds, headless) |",
        (
            f"| runtimes | Pyodide {env['pyodide']}, Textual {env['textual']}, "
            f"CPython {env['python']}, Node {env['node']} |"
        ),
    ]


def _before_after(
    data: results.ResultFile, baseline: results.ResultFile, columns: list[Column]
) -> list[str]:
    """Idle CPU of the same apps in an earlier run and in this one, side by side."""
    env = baseline["environment"]
    lines = [
        "### Idle CPU, before and after the input-only parser timer",
        "",
        (
            "Until the driver ticked its escape-sequence parser only after input, it ticked "
            "it every 50ms for the app's whole life. The earlier run "
            f"(`{env['commit']}`, {env['date'][:10]}) against this one, percent of one core:"
        ),
        "",
        *_header("", columns),
    ]
    for label, layer in (("static app", Layer.APP), ("blinking input", Layer.INPUT)):
        for when, source in (("before", baseline), ("after", data)):
            cells = [
                _format(
                    None
                    if (r := _record(source, column, f"idle/{layer}")) is None
                    else _cpu_percent(r),
                    2,
                )
                for column in columns
            ]
            lines.append(f"| {label}, {when} | {' | '.join(cells)} |")
    return lines


def render(path: Path, baseline: Path | None = None) -> str:
    """The whole include, as one string; `baseline` adds a before-and-after idle table."""
    data = results.read(path)
    columns = _columns(data)
    comparison = [] if baseline is None else [_before_after(data, results.read(baseline), columns)]
    sections = [
        [GENERATED_NOTE],
        _environment(data),
        _idle(data, columns),
        *comparison,
        _boot(data, columns),
        _memory(data, columns),
        _channel(data, columns),
        _controls(data, columns),
        _leaks(data, columns),
    ]
    return "\n\n".join("\n".join(section) for section in sections) + "\n"
